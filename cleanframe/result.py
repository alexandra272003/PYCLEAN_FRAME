"""
cleanframe/result.py
CleanResult — returned by every decorator.
"""
from __future__ import annotations

import textwrap
import pandas as pd


class CleanResult:
    """
    Returned by @clean, @audit, and @pipeline decorators.

    Attributes
    ----------
    df : pd.DataFrame
        The cleaned DataFrame.
    steps : list[dict]
        Structured log of every change made.
    return_value : any
        The value returned by the wrapped function (if any).
    func_name : str
        Name of the decorated function.
    """

    def __init__(self, df: pd.DataFrame, steps: list[dict], return_value=None, func_name: str = ""):
        self.df = df
        self.steps = steps
        self.return_value = return_value
        self.func_name = func_name

    # ── Human-readable report ──────────────────────────────────────────────

    def explain(self) -> str:
        """Return a human-readable report of all changes made."""
        active = [s for s in self.steps if s["action"] != "skip"]
        if not active:
            return f"cleanframe → {self.func_name}(): No changes needed. DataFrame was already clean."

        lines = [
            f"cleanframe → {self.func_name}() — Cleaning report",
            "=" * 55,
        ]

        for s in active:
            action = s["action"]
            col = s.get("column", "?")

            if action == "fill_null":
                strategy = s["strategy"]
                n = s["nulls_filled"]
                fv = s.get("fill_value")
                if fv is not None:
                    lines.append(f"  ✓ [{col}] Filled {n} null(s) using {strategy} → value: {fv!r}")
                else:
                    lines.append(f"  ✓ [{col}] Filled {n} null(s) using {strategy}")

            elif action == "clip":
                lines.append(
                    f"  ✓ [{col}] Clipped {s['before']} value(s) to range "
                    f"[{s['clip_min']}, {s['clip_max']}]"
                )

            elif action == "dtype":
                lines.append(f"  ✓ [{col}] Dtype coerced: {s['from']} → {s['to']}")

            elif action == "rename":
                lines.append(f"  ✓ [{col}] Renamed → '{s['to']}'")

        skipped = [s for s in self.steps if s["action"] == "skip"]
        if skipped:
            lines.append("")
            lines.append("  (columns not found, skipped silently:)")
            for s in skipped:
                lines.append(f"    - {s['column']}")

        lines.append("")
        lines.append(f"  DataFrame shape after cleaning: {self.df.shape}")
        return "\n".join(lines)

    # ── Equivalent pandas code ─────────────────────────────────────────────

    def to_code(self) -> str:
        """
        Return the equivalent pandas code as a string.
        No cleanframe dependency — copy-paste into any notebook.
        """
        active = [s for s in self.steps if s["action"] != "skip" and "code" in s]

        lines = [
            "import pandas as pd",
            "import numpy as np",
            "from numpy import nan",
            "",
            "# Generated by cleanframe — equivalent pandas code",
            "# Replace 'df' with your actual DataFrame variable",
            "",
            "df = df.copy()  # always work on a copy",
        ]

        if not active:
            lines.append("# No cleaning operations were needed")
        else:
            lines.append("")
            for s in active:
                col = s.get("column", "")
                action = s["action"]
                if action == "fill_null":
                    lines.append(f"# Fill nulls in '{col}' ({s['strategy']})")
                elif action == "clip":
                    lines.append(f"# Clip outliers in '{col}'")
                elif action == "dtype":
                    lines.append(f"# Coerce dtype of '{col}'")
                elif action == "rename":
                    lines.append(f"# Rename '{col}'")
                lines.append(s["code"])
                lines.append("")

        return "\n".join(lines)

    # ── One-liner summary ──────────────────────────────────────────────────

    def summary(self) -> str:
        """One-line summary of what was done."""
        fills = sum(1 for s in self.steps if s["action"] == "fill_null")
        clips = sum(1 for s in self.steps if s["action"] == "clip")
        dtypes = sum(1 for s in self.steps if s["action"] == "dtype")
        renames = sum(1 for s in self.steps if s["action"] == "rename")
        skips = sum(1 for s in self.steps if s["action"] == "skip")

        parts = []
        if fills:
            parts.append(f"{fills} null fill(s)")
        if clips:
            parts.append(f"{clips} clip(s)")
        if dtypes:
            parts.append(f"{dtypes} dtype coercion(s)")
        if renames:
            parts.append(f"{renames} rename(s)")
        if skips:
            parts.append(f"{skips} column(s) not found")

        body = ", ".join(parts) if parts else "no changes"
        return f"cleanframe [{self.func_name}]: {body} — shape {self.df.shape}"

    def __repr__(self):
        return (
            f"CleanResult(func={self.func_name!r}, "
            f"shape={self.df.shape}, "
            f"steps={len(self.steps)})"
        )
